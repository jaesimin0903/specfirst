#!/usr/bin/env node
// Writes src/gate/artifact.ts from the forge build of AllocationGate.sol (ABI and creation bytecode), so the CLI can
// deploy the gate without Foundry and the web can read it through @specfirst/core/gate. Run `forge build` in
// packages/contracts first. test/gate.test.ts ("bundled AllocationGate artifact") rebuilds with forge and checks the
// file against the build output.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '..', 'contracts', 'out', 'AllocationGate.sol', 'AllocationGate.json');
const dest = join(root, 'src', 'gate', 'artifact.ts');

const art = JSON.parse(await readFile(source, 'utf8'));
const out = `// Generated by scripts/gen-gate-artifact.mjs from packages/contracts/out/AllocationGate.sol (forge build).
// Regenerate after changing AllocationGate.sol; test/gate.test.ts checks it against a fresh forge build.
export const allocationGateAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const allocationGateBytecode = '${art.bytecode.object}' as const;
`;
await writeFile(dest, out);
console.log(`gen-gate-artifact: wrote ${art.abi.length} ABI entries and ${(art.bytecode.object.length - 2) / 2} bytecode bytes to ${dest}`);
