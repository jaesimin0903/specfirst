#!/usr/bin/env node
// Writes src/watch/demoArtifact.ts from the forge build of the watcher demo contracts (DemoVaultFactory,
// DemoVault, DemoToken in packages/contracts/src/demo), so tests and the demo can deploy them without Foundry.
// Run `forge build` in packages/contracts first. test/watch.test.ts ("bundled demo artifact") rebuilds with
// forge and checks the file against the build output; the CREATE2 address of the factory depends on it.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, '..', 'contracts', 'out');
const dest = join(root, 'src', 'watch', 'demoArtifact.ts');
const read = async (file, name) => JSON.parse(await readFile(join(out, file, `${name}.json`), 'utf8'));

const factory = await read('DemoVaultFactory.sol', 'DemoVaultFactory');
const vault = await read('DemoVaultFactory.sol', 'DemoVault');
const token = await read('DemoToken.sol', 'DemoToken');
const text = `// Generated by scripts/gen-demo-artifact.mjs from packages/contracts/out (forge build of src/demo).
// Regenerate after changing the demo contracts; test/watch.test.ts checks it against a fresh forge build.
export const demoVaultFactoryAbi = ${JSON.stringify(factory.abi, null, 2)} as const;

export const demoVaultFactoryBytecode = '${factory.bytecode.object}' as const;

export const demoVaultAbi = ${JSON.stringify(vault.abi, null, 2)} as const;

export const demoTokenAbi = ${JSON.stringify(token.abi, null, 2)} as const;

export const demoTokenBytecode = '${token.bytecode.object}' as const;
`;
await writeFile(dest, text);
console.log(`gen-demo-artifact: wrote DemoVaultFactory (${(factory.bytecode.object.length - 2) / 2} bytes), DemoVault ABI and DemoToken (${(token.bytecode.object.length - 2) / 2} bytes) to ${dest}`);
