#!/usr/bin/env node
// Writes src/desk/artifact.ts from the forge build of CheckRequestDesk.sol (ABI and creation bytecode), so the
// CLI can deploy the desk without Foundry and the web can read it through @specfirst/core/desk. Run
// `forge build` in packages/contracts first. test/desk.test.ts ("bundled CheckRequestDesk artifact") rebuilds
// with forge and checks the file against the build output.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '..', 'contracts', 'out', 'CheckRequestDesk.sol', 'CheckRequestDesk.json');
const dest = join(root, 'src', 'desk', 'artifact.ts');

const art = JSON.parse(await readFile(source, 'utf8'));
const out = `// Generated by scripts/gen-desk-artifact.mjs from packages/contracts/out/CheckRequestDesk.sol (forge build).
// Regenerate after changing CheckRequestDesk.sol; test/desk.test.ts checks it against a fresh forge build.
export const checkRequestDeskAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const checkRequestDeskBytecode = '${art.bytecode.object}' as const;
`;
await writeFile(dest, out);
console.log(`gen-desk-artifact: wrote ${art.abi.length} ABI entries and ${(art.bytecode.object.length - 2) / 2} bytecode bytes to ${dest}`);
