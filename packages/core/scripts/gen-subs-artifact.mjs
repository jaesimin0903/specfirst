#!/usr/bin/env node
// Writes src/subs/artifact.ts from the forge build of CheckSubscriptions.sol (ABI and creation bytecode), so the
// CLI can deploy the contract without Foundry and the web can read it through @specfirst/core/subs. Run
// `forge build` in packages/contracts first. test/subs.test.ts ("bundled CheckSubscriptions artifact") rebuilds
// with forge and checks the file against the build output.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '..', 'contracts', 'out', 'CheckSubscriptions.sol', 'CheckSubscriptions.json');
const dest = join(root, 'src', 'subs', 'artifact.ts');

const art = JSON.parse(await readFile(source, 'utf8'));
const out = `// Generated by scripts/gen-subs-artifact.mjs from packages/contracts/out/CheckSubscriptions.sol (forge build).
// Regenerate after changing CheckSubscriptions.sol; test/subs.test.ts checks it against a fresh forge build.
export const checkSubscriptionsAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const checkSubscriptionsBytecode = '${art.bytecode.object}' as const;
`;
await writeFile(dest, out);
console.log(`gen-subs-artifact: wrote ${art.abi.length} ABI entries and ${(art.bytecode.object.length - 2) / 2} bytecode bytes to ${dest}`);
