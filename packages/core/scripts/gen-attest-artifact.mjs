#!/usr/bin/env node
// Writes src/attest/artifact.ts from the forge build of CheckAttestationRegistry.sol (ABI and creation
// bytecode), so the CLI can deploy the registry without Foundry. Run `forge build` in packages/contracts
// first. test/attest.test.ts ("bundled CheckAttestationRegistry artifact") rebuilds with forge and checks the
// file against the build output.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, '..', 'contracts', 'out', 'CheckAttestationRegistry.sol', 'CheckAttestationRegistry.json');
const dest = join(root, 'src', 'attest', 'artifact.ts');

const art = JSON.parse(await readFile(source, 'utf8'));
const out = `// Generated by scripts/gen-attest-artifact.mjs from packages/contracts/out/CheckAttestationRegistry.sol (forge build).
// Regenerate after changing CheckAttestationRegistry.sol; test/attest.test.ts checks it against a fresh forge build.
export const checkAttestationRegistryAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const checkAttestationRegistryBytecode = '${art.bytecode.object}' as const;
`;
await writeFile(dest, out);
console.log(`gen-attest-artifact: wrote ${art.abi.length} ABI entries and ${(art.bytecode.object.length - 2) / 2} bytecode bytes to ${dest}`);
